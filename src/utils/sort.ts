/**
 * Компараторы для сортировок.
 *
 * ВАЖНО про localeCompare: на Hermes он не байтовое сравнение, а вызов через
 * JSI в нативный ICU-коллятор (android.icu.text.Collator / NSString) — это
 * ~500-1000× дороже обычного `<`. Для ISO-дат ('YYYY-MM-DD'), времени ('HH:MM')
 * и прочих ASCII-строк лексикографический порядок и так совпадает с нужным,
 * поэтому коллятор там — чистые потери: на 1500 клиентов сортировка занимала
 * десятки-сотни мс и роняла кадры прямо во время ввода в поиск.
 *
 * Коллятор оставляем только там, где сравниваются человеческие имена.
 */

/** По возрастанию для ASCII-строк (даты, время, id). */
export function cmpAsc(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** По убыванию для ASCII-строк (свежие сверху). */
export function cmpDesc(a: string, b: string): number {
  return a < b ? 1 : a > b ? -1 : 0;
}

/**
 * Коллятор для русских имён — создаётся ОДИН раз на модуль.
 * Создание Intl.Collator дороже самого сравнения, поэтому внутри sort-колбэка
 * его создавать нельзя.
 */
export const nameCollator = new Intl.Collator('ru');
