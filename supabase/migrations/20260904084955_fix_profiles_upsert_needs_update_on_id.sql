-- Починка полностью сломанной облачной синхронизации.
--
-- Симптом: у любого залогиненного мастера syncNow падал на первом же шаге —
--   «profiles upsert: permission denied for table profiles» (HTTP 403),
-- то есть НИ клиенты, ни записи, ни финансы не уезжали в облако вообще.
-- Найдено запуском приложения в симуляторе (в логе crashReporter).
--
-- Причина: миграция profiles_column_level_grants перевела profiles на
-- колоночные гранты и намеренно НЕ дала UPDATE на id. Но клиент шлёт
-- supabase.from('profiles').upsert({...}), а PostgREST разворачивает это в
--   insert ... on conflict (id) do update set id = excluded.id, name = ...
-- то есть в список UPDATE попадает и сам id → отказ по правам.
-- Проверено: обычный PATCH проходит (204), upsert падает (403) даже когда в
-- теле нет ничего кроме id.
--
-- Почему грант на id безопасен: у политики «Users can update own profile»
-- отдельного WITH CHECK нет, поэтому Postgres применяет USING-выражение и на
-- запись — строка обязана остаться с id = auth.uid(). Переписать id на чужой
-- нельзя; on conflict может присвоить только то же самое значение.
-- INSERT-политика тоже прибита к auth.uid() = id.
--
-- ВНИМАНИЕ на будущее: этот грант связан с тем, что клиент делает upsert.
-- Не убирать его, не изменив сначала pushAll в src/lib/cloudSync.ts, — иначе
-- синхронизация снова молча ляжет у всех уже установленных версий.
grant update (id) on public.profiles to authenticated;
